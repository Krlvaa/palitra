// Downloads the Cyrillic + Latin subsets of the project fonts and writes a
// self-hosted @font-face stylesheet. Run once with `node scripts/fonts.mjs`.
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const FONTS = [
  {
    family: "Cormorant Garamond",
    query: "Cormorant+Garamond:ital,wght@0,400;0,500;0,600;1,400",
    prefix: "cormorant",
  },
  {
    family: "Inter",
    query: "Inter:wght@400;500;600",
    prefix: "inter",
  },
];

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36";

const outDir = path.join(process.cwd(), "public", "fonts");
await mkdir(outDir, { recursive: true });

function subsetFromRange(range) {
  if (range.includes("U+0301")) return "cyrillic";
  if (range.includes("U+0100")) return "latin-ext";
  if (range.includes("U+0000")) return "latin";
  return null;
}

let css = `/* Self-hosted fonts. Generated by scripts/fonts.mjs — do not edit by hand. */\n`;

for (const font of FONTS) {
  const url = `https://fonts.googleapis.com/css2?family=${font.query}&display=swap`;
  const response = await fetch(url, { headers: { "User-Agent": UA } });
  const sheet = await response.text();

  const blocks = sheet.match(/@font-face\s*{[^}]+}/g) ?? [];
  for (const block of blocks) {
    const style = block.match(/font-style:\s*(\w+)/)?.[1] ?? "normal";
    const weight = block.match(/font-weight:\s*(\d+)/)?.[1] ?? "400";
    const src = block.match(/url\((https:[^)]+\.woff2)\)/)?.[1];
    const range = block.match(/unicode-range:\s*([^;]+);/)?.[1] ?? "";
    if (!src) continue;

    const subset = subsetFromRange(range);
    if (subset !== "cyrillic" && subset !== "latin") continue;

    const fileName = `${font.prefix}-${weight}-${style}-${subset}.woff2`;
    const file = await fetch(src, { headers: { "User-Agent": UA } });
    if (!file.ok) throw new Error(`Failed to download ${src}`);
    await writeFile(path.join(outDir, fileName), Buffer.from(await file.arrayBuffer()));

    css += `
@font-face {
  font-family: '${font.family}';
  font-style: ${style};
  font-weight: ${weight};
  font-display: swap;
  src: url('/fonts/${fileName}') format('woff2');
  unicode-range: ${range};
}
`;
    console.log(`saved ${fileName}`);
  }
}

await writeFile(path.join(process.cwd(), "src", "app", "fonts.css"), css);
console.log("wrote src/app/fonts.css");
